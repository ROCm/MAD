#!/usr/bin/env python3
"""Model Configuration Validator

Validates models.json entries for:
- Required fields presence
- Naming conventions
- Field types
- Cross-field consistency
- Framework-specific requirements
- File references, the Dockerfile CONTEXT header, and the output contract

Registry discovery mirrors madengine (madengine/utils/discover_models.py): the
root models.json plus every models.json / get_models_json.py found by walking
scripts/ recursively. Run with no arguments to validate every registered model.
"""

import ast
import json
import os
import re
import shutil
import subprocess
import sys
from typing import Dict, List, Optional, Tuple

# Repo root, derived from this file's location (tools/validation/) so registry
# discovery does not depend on the caller's current working directory.
REPO_ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))


def _str_field(model_entry: dict, field: str) -> str:
    """Return model_entry[field] if it is a string, else ''.

    Type errors are reported by _check_field_types; name/path-dependent checks
    use this so malformed values are skipped instead of crashing.
    """
    value = model_entry.get(field, '')
    return value if isinstance(value, str) else ''


def check_dockerfile_context_header(dockerfile_path: str) -> Optional[str]:
    """Return an error message if the Dockerfile lacks a usable CONTEXT header.

    madengine reads the header with `head -n5 <dockerfile> | grep '# CONTEXT '`,
    so it must sit in the first five lines and hold a dict whose gpu_vendor
    names AMD.
    """
    try:
        with open(dockerfile_path, errors='ignore') as f:
            head = [f.readline() for _ in range(5)]
    except OSError as e:
        return f"Cannot read Dockerfile ({e})"
    for line in head:
        if line.startswith('# CONTEXT '):
            try:
                context = ast.literal_eval(line[len('# CONTEXT '):].strip())
            except (ValueError, SyntaxError):
                return "Dockerfile CONTEXT header is not a valid dict literal"
            if not isinstance(context, dict) or 'AMD' not in str(context.get('gpu_vendor', '')):
                return "Dockerfile CONTEXT header has no gpu_vendor 'AMD'"
            return None
    return ("Dockerfile has no '# CONTEXT {...}' header in its first 5 lines "
            "(expected: # CONTEXT {'gpu_vendor': 'AMD', 'guest_os': 'UBUNTU'})")


def _dir_emits_performance_line(directory: str) -> bool:
    """True if any text file under `directory` has a non-comment 'performance:' line."""
    for root, dirs, files in os.walk(directory):
        dirs[:] = [d for d in dirs if not d.startswith('.')]
        for name in files:
            path = os.path.join(root, name)
            try:
                if os.path.getsize(path) > 2 * 1024 * 1024:
                    continue
                with open(path, 'rb') as f:
                    data = f.read()
            except OSError:
                continue
            if b'\0' in data[:1024]:
                continue  # binary
            for line in data.decode('utf-8', errors='ignore').splitlines():
                stripped = line.strip()
                if 'performance:' in stripped and not stripped.startswith('#'):
                    return True
    return False


class ModelConfigValidator:
    """Validator for MAD model configuration entries"""

    REQUIRED_FIELDS = ['name', 'dockerfile', 'scripts', 'n_gpus', 'owner', 'tags']
    OPTIONAL_FIELDS = ['url', 'data', 'timeout', 'multiple_results',
                       'training_precision', 'skip_gpu_arch']

    # Framework-specific validation rules
    FRAMEWORK_RULES = {
        'pyt_vllm': {
            'required_tags': ['pyt', 'vllm'],
            'recommended_args': ['--config', '--model_repo'],
        },
        'pyt_sglang': {
            'required_tags': ['pyt', 'sglang'],
            'recommended_args': ['--model_repo', '--test_option'],
        },
        'jax_maxtext': {
            'required_tags': ['jax'],
        },
    }

    def __init__(self, verbose: bool = True, base_dir: str = '.',
                 allow_missing_files: bool = False):
        self.verbose = verbose
        self.base_dir = base_dir
        self.allow_missing_files = allow_missing_files
        self.errors: List[str] = []
        self.warnings: List[str] = []

    def validate(self, model_entry: dict, dynamic: bool = False) -> bool:
        """
        Validate a model configuration entry

        Args:
            model_entry: Dictionary containing model configuration
            dynamic: The entry was generated by a get_models_json.py. Its
                name and metadata come from code, so only file references,
                the Dockerfile header and the output contract are checked.

        Returns:
            True if validation passes (warnings OK), False if errors found
        """
        self.errors = []
        self.warnings = []

        if not isinstance(model_entry, dict):
            self.errors.append(
                f"Model entry must be a JSON object, got {type(model_entry).__name__}"
            )
            if self.verbose:
                self._print_report('Unknown')
            return False

        if not dynamic:
            # Level 1: Required fields
            self._check_required_fields(model_entry)

            # Level 2: Naming convention
            self._check_naming_convention(model_entry)

            # Level 3: Field types
            self._check_field_types(model_entry)

            # Level 4: Cross-field consistency
            self._check_cross_field_consistency(model_entry)

            # Level 5: Framework-specific rules
            self._check_framework_rules(model_entry)

        # Level 6: File references, Dockerfile header, output contract
        self._check_file_references(model_entry)
        self._check_output_contract(model_entry)

        if self.verbose:
            self._print_report(model_entry.get('name', 'Unknown'))

        return len(self.errors) == 0

    def _check_required_fields(self, model_entry: dict):
        """Check all required fields are present"""
        for field in self.REQUIRED_FIELDS:
            if field not in model_entry:
                self.errors.append(f"Missing required field: {field}")
            elif not model_entry[field]:
                self.errors.append(f"Required field is empty: {field}")

    def _check_naming_convention(self, model_entry: dict):
        """Validate naming follows {framework}_{project}_{workload} pattern"""
        name = model_entry.get('name', '')
        if name is None:
            return  # already reported by _check_required_fields
        if not isinstance(name, str):
            return  # reported by _check_field_types

        # Check format
        if not re.match(r'^[a-z]+_[a-z0-9_.\-]+$', name):
            self.errors.append(
                f"Invalid name format: '{name}'. "
                "Must match pattern: {framework}_{project}_{workload} "
                "(lowercase, alphanumeric, underscores, hyphens only)"
            )
            return

        # Check at least 2 components
        parts = name.split('_')
        if len(parts) < 2:
            self.errors.append(
                f"Name must have at least 2 components: {name}"
            )

    def _check_field_types(self, model_entry: dict):
        """Verify field types are correct"""
        # name, dockerfile, scripts and owner must be strings
        for field in ('name', 'dockerfile', 'scripts', 'owner'):
            value = model_entry.get(field)
            if value is not None and not isinstance(value, str):
                self.errors.append(f"Field '{field}' must be a string")

        # tags must be a list
        if 'tags' in model_entry:
            if not isinstance(model_entry['tags'], list):
                self.errors.append(f"Field 'tags' must be a list")
            elif len(model_entry['tags']) == 0:
                self.warnings.append(f"Field 'tags' is empty")

        # n_gpus must be a string (for backward compatibility)
        if 'n_gpus' in model_entry:
            if not isinstance(model_entry['n_gpus'], str):
                self.errors.append(f"Field 'n_gpus' must be a string")

        # timeout must be a number if present
        if 'timeout' in model_entry:
            timeout = model_entry['timeout']
            if isinstance(timeout, bool) or not isinstance(timeout, (int, float)):
                self.errors.append(f"Field 'timeout' must be a number")

        # args must be present and a string (the runtime indexes model['args']
        # unconditionally and appends it to the shell command, so a missing
        # or non-string value breaks at run time; unlike other required
        # fields, an empty string is valid here)
        if 'args' not in model_entry:
            self.errors.append(f"Missing required field: args")
        elif not isinstance(model_entry['args'], str):
            self.errors.append(f"Field 'args' must be a string")

    def _check_cross_field_consistency(self, model_entry: dict):
        """Check fields are consistent with each other"""
        name = _str_field(model_entry, 'name')
        tags = model_entry.get('tags', [])

        # Framework tag should match name prefix (skip if tags isn't a list;
        # _check_field_types already records an error for that case)
        if name and tags and isinstance(tags, list):
            framework_prefix = name.split('_')[0]
            if framework_prefix not in tags:
                self.warnings.append(
                    f"Framework tag '{framework_prefix}' not in tags list. "
                    f"Tags: {tags}"
                )

        # Dockerfile path should match naming pattern
        dockerfile = _str_field(model_entry, 'dockerfile')
        if dockerfile and name:
            expected_prefix = '_'.join(name.split('_')[:2])  # e.g., pyt_vllm
            if expected_prefix not in dockerfile:
                self.warnings.append(
                    f"Dockerfile path '{dockerfile}' doesn't match expected "
                    f"pattern 'docker/{expected_prefix}'"
                )

    def _check_framework_rules(self, model_entry: dict):
        """Apply framework-specific validation rules"""
        name = _str_field(model_entry, 'name')
        if not name:
            return

        # Determine framework key (first two components)
        framework_key = '_'.join(name.split('_')[:2])

        if framework_key not in self.FRAMEWORK_RULES:
            return  # No specific rules for this framework

        rules = self.FRAMEWORK_RULES[framework_key]
        tags = model_entry.get('tags', [])
        args = model_entry.get('args', '')

        # Check required tags (skip if tags isn't a list; _check_field_types
        # already records an error for that case)
        if 'required_tags' in rules and isinstance(tags, list):
            for req_tag in rules['required_tags']:
                if req_tag not in tags:
                    self.errors.append(
                        f"Missing required tag for {framework_key}: {req_tag}"
                    )

        # Check recommended args (run even when args is empty/omitted, so a
        # model with no args at all is still flagged for missing recommendations).
        # Skip if args isn't a string (e.g. null) rather than crashing on `in`.
        if 'recommended_args' in rules and isinstance(args, str):
            for rec_arg in rules['recommended_args']:
                if rec_arg not in args:
                    self.warnings.append(
                        f"Recommended argument missing: {rec_arg}"
                    )

        # Check required fields for framework
        if 'required_fields' in rules:
            for req_field in rules['required_fields']:
                if req_field not in model_entry or not model_entry[req_field]:
                    self.errors.append(
                        f"Required field for {framework_key}: {req_field}"
                    )

    def _check_file_references(self, model_entry: dict):
        """Verify referenced files and directories exist.

        Paths in model_entry (dockerfile, scripts) are relative to the
        directory containing the models.json file, not the process cwd.
        """
        dockerfile = _str_field(model_entry, 'dockerfile')
        if dockerfile:
            dockerfile_path = os.path.normpath(
                os.path.join(self.base_dir, f"{dockerfile}.ubuntu.amd.Dockerfile")
            )
            if not os.path.exists(dockerfile_path):
                message = f"Dockerfile not found: {dockerfile_path}"
                if self.allow_missing_files:
                    self.warnings.append(f"{message} (OK if generating a new model)")
                else:
                    self.errors.append(message)
            else:
                header_error = check_dockerfile_context_header(dockerfile_path)
                if header_error:
                    self.errors.append(f"{header_error}: {dockerfile_path}")

        scripts = _str_field(model_entry, 'scripts')
        if scripts:
            scripts_path = os.path.normpath(os.path.join(self.base_dir, scripts))
            if not os.path.exists(scripts_path):
                message = f"Scripts path not found: {scripts_path}"
                if self.allow_missing_files:
                    self.warnings.append(f"{message} (OK if generating a new model)")
                else:
                    self.errors.append(message)

    def _check_output_contract(self, model_entry: dict):
        """Check the model reports a result madengine can record.

        A model either sets multiple_results (its script writes that CSV) or
        prints a 'performance: <value> <unit>' line. The line may come from a
        helper the run script calls, so every text file in the script's
        directory is searched. slurm_multi models are exempt: their job writes
        perf.csv itself and madengine collects it.
        """
        if model_entry.get('multiple_results'):
            return
        distributed = model_entry.get('distributed')
        if isinstance(distributed, dict) and distributed.get('launcher') == 'slurm_multi':
            return
        scripts = _str_field(model_entry, 'scripts')
        if not scripts:
            return  # reported by _check_required_fields
        scripts_path = os.path.normpath(os.path.join(self.base_dir, scripts))
        if not os.path.exists(scripts_path):
            return  # reported by _check_file_references
        search_dir = scripts_path if os.path.isdir(scripts_path) else os.path.dirname(scripts_path)
        if not _dir_emits_performance_line(search_dir):
            self.errors.append(
                "No output contract: no 'performance: <value> <unit>' line in "
                f"{search_dir} and no 'multiple_results' field"
            )

    def _print_report(self, model_name: str):
        """Print validation report"""
        print(f"\nModel Validation Report for: {model_name}")
        print("=" * 60)

        if self.errors:
            print(f"\n❌ ERRORS ({len(self.errors)}):")
            for i, error in enumerate(self.errors, 1):
                print(f"  {i}. {error}")

        if self.warnings:
            print(f"\n⚠️  WARNINGS ({len(self.warnings)}):")
            for i, warning in enumerate(self.warnings, 1):
                print(f"  {i}. {warning}")

        if not self.errors and not self.warnings:
            print("\n✅ All validation checks passed!")
        elif not self.errors:
            print(f"\n✅ No errors found ({len(self.warnings)} warnings)")
        else:
            print(f"\n❌ Validation failed: {len(self.errors)} errors, "
                  f"{len(self.warnings)} warnings")

        print()


def _walk_registry_dirs(repo_root: str = REPO_ROOT):
    """Yield (dirpath, files) for every directory under scripts/, like madengine."""
    scripts_dir = os.path.join(repo_root, 'scripts')
    for root, dirs, files in os.walk(scripts_dir):
        dirs.sort()
        if os.path.relpath(root, scripts_dir) == '.':
            continue
        yield root, files


def registry_scope(registry_dir: str, repo_root: str = REPO_ROOT) -> str:
    """Return the name prefix madengine gives models registered in `registry_dir`.

    Mirrors discover_models.py: scripts/vllm -> 'vllm'; for nested submodules,
    A/scripts/B -> 'A/B'. The root models.json has no prefix ('').
    """
    scripts_dir = os.path.join(repo_root, 'scripts')
    rel_path = os.path.relpath(registry_dir, scripts_dir)
    if rel_path == '.' or rel_path.startswith('..'):
        return ''
    parts = rel_path.split(os.sep)
    last = -1
    for i, part in enumerate(parts):
        if part.lower() == 'scripts':
            last = i
    if last >= 1:
        parts = [parts[last - 1]] + parts[last + 1:]
    elif last == 0:
        parts = parts[1:]
    return '/'.join(parts) if parts else rel_path


def discover_registry_files(repo_root: str = REPO_ROOT) -> List[str]:
    """Find every models.json registry file in the repo.

    Models are registered in per-directory models.json files found by walking
    scripts/ recursively, the same way madengine discovers them. The root
    models.json (normally []) is included because madengine reads it too.
    """
    paths = []
    root_json = os.path.join(repo_root, 'models.json')
    if os.path.exists(root_json):
        paths.append(root_json)
    for root, files in _walk_registry_dirs(repo_root):
        if 'models.json' in files:
            paths.append(os.path.join(root, 'models.json'))
    return paths


def discover_dynamic_registry_dirs(repo_root: str = REPO_ROOT) -> List[str]:
    """Find every directory under scripts/ that registers models from code."""
    return [root for root, files in _walk_registry_dirs(repo_root)
            if 'get_models_json.py' in files]


def find_registry_conflicts(repo_root: str = REPO_ROOT) -> List[str]:
    """Directories with both models.json and get_models_json.py (madengine rejects them)."""
    return [
        f"Both models.json and get_models_json.py found in {_display_path(root, repo_root)}; "
        "madengine refuses to discover this directory"
        for root, files in _walk_registry_dirs(repo_root)
        if 'models.json' in files and 'get_models_json.py' in files
    ]


def expand_dynamic_models(registry_dir: str,
                          repo_root: str = REPO_ROOT) -> Tuple[Optional[list], str]:
    """Expand a get_models_json.py directory through `madengine discover`.

    Returns (models, note). models is None when the expansion could not run;
    note then says why. Paths in the returned entries are relative to the
    repo root, as madengine resolves them.
    """
    if not shutil.which('madengine'):
        return None, 'madengine is not installed, so its get_models_json.py models were not checked'
    scope = registry_scope(registry_dir, repo_root)
    env = dict(os.environ)
    env.pop('MODEL_DIR', None)  # keep discovery from copying files into the repo
    try:
        proc = subprocess.run(
            ['madengine', 'discover', '--tags', f'{scope}/all', '--json'],
            cwd=repo_root, env=env, capture_output=True, text=True, timeout=300,
        )
    except (OSError, subprocess.TimeoutExpired) as e:
        return None, f'madengine discover failed: {e}'
    start = proc.stdout.find('[')
    if proc.returncode != 0 or start < 0:
        detail = (proc.stderr or proc.stdout).strip().splitlines()[-1:] or ['no output']
        return None, f'madengine discover failed: {detail[0]}'
    try:
        models, _ = json.JSONDecoder().raw_decode(proc.stdout[start:])
    except json.JSONDecodeError as e:
        return None, f'madengine discover returned invalid JSON: {e}'
    if not isinstance(models, list):
        return None, 'madengine discover did not return a list'
    return models, ''


def _display_path(path: str, repo_root: str = REPO_ROOT) -> str:
    """Show a registry path relative to the repo root when it is inside it."""
    real_path, real_root = os.path.realpath(path), os.path.realpath(repo_root)
    if os.path.commonpath([real_path, real_root]) == real_root:
        return os.path.relpath(real_path, real_root)
    return path


def _model_names(models: list) -> List[str]:
    """Return the string names of the dict entries in `models`, in order.

    Malformed entries are skipped here; ModelConfigValidator reports them.
    """
    return [m['name'] for m in models
            if isinstance(m, dict) and isinstance(m.get('name'), str) and m['name']]


def load_registry(models_json_path: str) -> Optional[list]:
    """Load a models.json file, printing an error and returning None if it
    is missing, not valid JSON, or not a top-level list."""
    try:
        with open(models_json_path, 'r') as f:
            models = json.load(f)
    except FileNotFoundError:
        print(f"Error: {models_json_path} not found")
        return None
    except json.JSONDecodeError as e:
        print(f"Error: Invalid JSON in {models_json_path}: {e}")
        return None

    if not isinstance(models, list):
        print(f"Error: {models_json_path} must contain a JSON array of model "
              f"entries, got {type(models).__name__}")
        return None
    return models


def find_cross_registry_duplicates(repo_root: str = REPO_ROOT) -> Dict[str, List[str]]:
    """Return {name: [files]} for model names registered in more than one file.

    Names must be unique across the whole registry, not just within a single
    models.json, since --model/--tags lookups match the first occurrence.
    """
    name_to_files: Dict[str, List[str]] = {}
    for path in discover_registry_files(repo_root):
        try:
            with open(path, 'r') as f:
                models = json.load(f)
        except (FileNotFoundError, json.JSONDecodeError):
            continue
        if not isinstance(models, list):
            continue
        for name in _model_names(models):
            name_to_files.setdefault(name, []).append(path)
    return {name: files for name, files in name_to_files.items() if len(files) > 1}


def check_duplicate_names(models_json_path: str, models: list,
                          repo_root: str = REPO_ROOT) -> List[str]:
    """Return error messages for any model name duplicated within `models`
    or registered in another models.json registry file elsewhere in the repo.

    Shared by both the all-model and single-model (--model) validation paths
    so a duplicate is reported consistently regardless of which is used.
    Paths are compared by realpath, so relative, absolute and symlinked
    spellings of the same file all match.
    """
    errors: List[str] = []
    seen_names: Dict[str, int] = {}
    for name in _model_names(models):
        if name in seen_names:
            errors.append(
                f"Duplicate model name: '{name}' appears more than once in {models_json_path}"
            )
        else:
            seen_names[name] = 1

    cross_duplicates = find_cross_registry_duplicates(repo_root)
    real_path = os.path.realpath(models_json_path)
    for name, files in cross_duplicates.items():
        real_files = {os.path.realpath(f) for f in files}
        if real_path in real_files and len(real_files) > 1:
            other_files = sorted(_display_path(f, repo_root)
                                 for f in real_files if f != real_path)
            errors.append(
                f"Duplicate model name across registries: '{name}' also "
                f"registered in: {', '.join(other_files)}"
            )
    return errors


def validate_models_json(models_json_path: str = "models.json",
                          allow_missing_files: bool = False,
                          repo_root: str = REPO_ROOT) -> bool:
    """
    Validate all models in one models.json file

    Args:
        models_json_path: Path to models.json file
        allow_missing_files: Treat missing Dockerfile/script references as
            warnings instead of errors (for models still being generated)

    Returns:
        True if all models are valid, False otherwise (including when the
        file has no model entries, so an empty registry never reads as a pass)
    """
    models = load_registry(models_json_path)
    if models is None:
        return False
    if not models:
        print(f"Error: {models_json_path} has no model entries, so nothing was validated. "
              "Models are registered per directory; run without --models-json to "
              "validate every registry.")
        return False

    base_dir = os.path.dirname(models_json_path) or '.'
    validator = ModelConfigValidator(verbose=True, base_dir=base_dir,
                                      allow_missing_files=allow_missing_files)
    all_valid = True

    for model in models:
        if not validator.validate(model):
            all_valid = False

    for message in check_duplicate_names(models_json_path, models, repo_root):
        print(f"\n❌ {message}")
        all_valid = False

    return all_valid


def _selected(model: dict, scope: str, model_name: Optional[str], tag: Optional[str]) -> bool:
    """Mirror madengine's unscoped --tags matching for --model / --tag.

    A model matches by full name (scope/name), bare name, or tag; 'all'
    matches everything. With neither selector, every entry is selected.
    """
    if model_name is None and tag is None:
        return True
    if not isinstance(model, dict):
        return False
    name = _str_field(model, 'name')
    full = f"{scope}/{name}" if scope and name else name
    names = {name, full, full.split('/')[-1]} - {''}
    if model_name is not None and model_name in names:
        return True
    if tag is not None:
        tags = model.get('tags')
        if isinstance(tags, str):
            tags = [t.strip() for t in tags.split(',')]
        if tag == 'all' or tag in names or (isinstance(tags, list) and tag in tags):
            return True
    return False


def validate_registries(repo_root: str = REPO_ROOT, model_name: Optional[str] = None,
                        tag: Optional[str] = None,
                        allow_missing_files: bool = False,
                        require_dynamic: bool = False) -> bool:
    """Validate every registered model, or only those matching --model/--tag.

    Covers the root models.json, every models.json under scripts/ (recursive),
    and get_models_json.py models when madengine is installed. Fails when no
    model was validated, so an empty or mistyped selection never passes. With
    require_dynamic, a get_models_json.py directory that could not be expanded
    is an error instead of a warning (for CI, where madengine is installed).
    """
    all_valid = True
    for message in find_registry_conflicts(repo_root):
        print(f"\n❌ {message}")
        all_valid = False

    registry_files = discover_registry_files(repo_root)
    checked = 0
    for path in registry_files:
        models = load_registry(path)
        if models is None:
            all_valid = False
            continue
        scope = registry_scope(os.path.dirname(path), repo_root)
        selected = [m for m in models if _selected(m, scope, model_name, tag)]
        if not selected:
            continue
        validator = ModelConfigValidator(verbose=True, base_dir=os.path.dirname(path),
                                          allow_missing_files=allow_missing_files)
        for model in selected:
            checked += 1
            if not validator.validate(model):
                all_valid = False
        selected_names = {f"'{_str_field(m, 'name')}'" for m in selected if isinstance(m, dict)}
        for message in check_duplicate_names(path, models, repo_root):
            if model_name is None and tag is None or any(n in message for n in selected_names):
                print(f"\n❌ {message}")
                all_valid = False

    dynamic_skipped = []
    for registry_dir in discover_dynamic_registry_dirs(repo_root):
        models, note = expand_dynamic_models(registry_dir, repo_root)
        if models is None:
            dynamic_skipped.append(f"{_display_path(registry_dir, repo_root)}: {note}")
            continue
        validator = ModelConfigValidator(verbose=True, base_dir=repo_root,
                                          allow_missing_files=allow_missing_files)
        for model in models:
            if _selected(model, '', model_name, tag):
                checked += 1
                if not validator.validate(model, dynamic=True):
                    all_valid = False

    for message in dynamic_skipped:
        if require_dynamic:
            print(f"\n❌ Not checked: {message}")
            all_valid = False
        else:
            print(f"\n⚠️  Not checked: {message}")
    print(f"\nValidated {checked} model(s) from {len(registry_files)} models.json file(s)"
          + (f"; {len(dynamic_skipped)} get_models_json.py director(ies) not checked"
             if dynamic_skipped else ""))
    if checked == 0:
        selector = f"--model {model_name}" if model_name else f"--tag {tag}" if tag else "all"
        print(f"Error: no models matched {selector}, so nothing was validated")
        return False
    return all_valid


def validate_all_registries(allow_missing_files: bool = False,
                            repo_root: str = REPO_ROOT) -> bool:
    """Validate every registered model in the repo (see validate_registries)."""
    return validate_registries(repo_root, allow_missing_files=allow_missing_files)


if __name__ == '__main__':
    import argparse

    parser = argparse.ArgumentParser(
        description='Validate MAD model configurations. With no arguments, validates '
                    'every registered model (root models.json, every models.json under '
                    'scripts/, and get_models_json.py models when madengine is installed).')
    parser.add_argument('--models-json',
                       help='Validate only this models.json file (paths in it are '
                            'resolved relative to its directory)')
    parser.add_argument('--model',
                       help='Validate one model by name (bare name or dir/name). '
                            'Searches every registry unless --models-json is given')
    parser.add_argument('--tag', help='Validate the models carrying this tag')
    parser.add_argument('--all', action='store_true',
                       help='Validate every registered model (the default)')
    parser.add_argument('--allow-missing-files', action='store_true',
                       help='Treat missing Dockerfile/script references as '
                            'warnings instead of errors (for models still '
                            'being generated)')
    parser.add_argument('--require-dynamic', action='store_true',
                       help='Fail when a get_models_json.py directory cannot be expanded '
                            '(e.g. madengine is not installed); use in CI')
    parser.add_argument('--repo-root', default=REPO_ROOT,
                       help='MAD repository root (default: derived from this file)')

    args = parser.parse_args()
    repo_root = os.path.abspath(args.repo_root)

    if args.models_json and args.tag:
        parser.error('--tag searches every registry; drop --models-json')

    if args.models_json and args.model:
        # Validate one model from one registry file
        try:
            models = load_registry(args.models_json)
            if models is None:
                sys.exit(1)

            model_entry = None
            for m in models:
                if isinstance(m, dict) and m.get('name') == args.model:
                    model_entry = m
                    break

            if not model_entry:
                print(f"Error: Model '{args.model}' not found in {args.models_json}")
                sys.exit(1)

            base_dir = os.path.dirname(args.models_json) or '.'
            validator = ModelConfigValidator(verbose=True, base_dir=base_dir,
                                              allow_missing_files=args.allow_missing_files)
            valid = validator.validate(model_entry)

            for message in check_duplicate_names(args.models_json, models, repo_root):
                if f"'{args.model}'" in message:
                    print(f"\n❌ {message}")
                    valid = False

            sys.exit(0 if valid else 1)

        except Exception as e:
            print(f"Error: {e}")
            sys.exit(1)
    elif args.models_json:
        # Validate a single models.json file
        valid = validate_models_json(args.models_json, args.allow_missing_files, repo_root)
        sys.exit(0 if valid else 1)
    else:
        # Validate every registry, optionally narrowed by --model / --tag
        valid = validate_registries(repo_root, args.model, args.tag,
                                    args.allow_missing_files, args.require_dynamic)
        sys.exit(0 if valid else 1)
